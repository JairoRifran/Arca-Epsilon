import { copyFile, mkdir, readFile, rename, stat, unlink, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadEnvLocal } from './load-env-local.mjs';

/**
 * Mission 13 "La Primera Tormenta" — non-vocal audio generator.
 *
 * Generates the ambience, sound effects and score for M13 through the same
 * ElevenLabs endpoints the project already uses in
 * `generate-elevenlabs-audio.mjs`:
 *
 *   - music  -> POST /v1/music            (model music_v1, force_instrumental)
 *   - sfx    -> POST /v1/sound-generation (model eleven_text_to_sound_v2)
 *
 * The sound-generation endpoint takes a `loop` flag, which is what makes the
 * seamless ambience beds genuinely loopable rather than faded copies.
 *
 * Voices are NOT touched here. They are already generated by
 * `npm run audio:generate:voices` and live under /audio/voices/.
 *
 * No manifest is written. Unlike the main pipeline — whose assets are indexed
 * in public/audio/audio-manifest.json — Mission 13 audio is declared
 * statically in src/audio/audioDefinitions.ts (MISSION13_STATIC_ASSETS) and
 * registered directly by AudioManager, which proves each file's existence by
 * fetching it. Dropping a valid MP3 into these paths is all the game needs.
 *
 * Usage (from CMD or PowerShell):
 *   npm run audio:generate:m13
 *   npm run audio:generate:m13 -- --category=ambience
 *   npm run audio:generate:m13 -- --only=m13-storm-peak,m13-shield-activated
 *   npm run audio:generate:m13 -- --list
 *   npm run audio:generate:m13 -- --dry-run
 *   npm run audio:generate:m13 -- --force
 */

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const missionRoot = join(projectRoot, 'public', 'audio', 'mission-13');
const musicDirectory = join(missionRoot, 'music');
const ambienceDirectory = join(missionRoot, 'ambience');
