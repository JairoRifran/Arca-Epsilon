// ---------------------------------------------------------------------------
// CLI
// ---------------------------------------------------------------------------

const args = process.argv.slice(2);
const force = args.includes('--force');
const dryRun = args.includes('--dry-run');
const listOnly = args.includes('--list');
const category = getCategory(args);
const requested = getRequestedNames(args);

let selected = category ? catalog.filter((asset) => asset.group === category) : catalog;
if (requested.size > 0) {
  selected = selected.filter((asset) => requested.has(asset.name));
  const known = new Set(catalog.map((asset) => asset.name));
  const unknown = [...requested].filter((name) => !known.has(name));
  if (unknown.length > 0) {
    process.stderr.write(`Unknown Mission 13 audio asset: ${unknown.join(', ')}\n`);
    process.exit(1);
  }
}

if (listOnly) {
  process.stdout.write(`Mission 13 audio catalog (${catalog.length} assets)\n\n`);
  for (const asset of catalog) {
    const exists = await isValidMp3File(targetPathFor(asset));
    const flag = exists ? 'present' : 'MISSING';
    process.stdout.write(
      `  [${flag.padEnd(7)}] ${asset.group.padEnd(8)} ${asset.name.padEnd(34)} ${asset.loop ? 'loop    ' : 'one-shot'} ${asset.durationSeconds}s\n`
    );
  }
  process.exit(0);
}

await mkdir(musicDirectory, { recursive: true });
await mkdir(ambienceDirectory, { recursive: true });
await mkdir(sfxDirectory, { recursive: true });

// Work out what actually needs generating before asking for a key, so a
// dry run and a fully-populated folder never require credentials.
const pending = [];
for (const asset of selected) {
  const existing = await isValidMp3File(targetPathFor(asset));
  if (!force && existing) {
    process.stdout.write(`Skipped existing audio: ${asset.name}.mp3\n`);
    continue;
  }
  pending.push(asset);
}

if (dryRun) {
  process.stdout.write(`\nDry run: ${pending.length} asset(s) would be generated.\n`);
  for (const asset of pending) process.stdout.write(`  - ${asset.group}/${asset.name}.mp3\n`);
  process.exit(0);
}

if (pending.length === 0) {
  process.stdout.write('\nMission 13 audio already complete: nothing to generate.\n');
  await reportCoverage();
  process.exit(0);
}

await loadEnvLocal(projectRoot, ['ELEVENLABS_API_KEY']);
const apiKey = process.env.ELEVENLABS_API_KEY?.trim();
if (!apiKey || apiKey === 'PASTE_KEY_HERE' || apiKey === 'your_elevenlabs_api_key_here') {
  process.stderr.write('Missing ELEVENLABS_API_KEY in .env.local\n');
  process.exit(1);
}

const failures = [];
for (const asset of pending) {
  const targetPath = targetPathFor(asset);
  process.stdout.write(`Generating ${asset.group}: ${asset.name}.mp3 (${asset.durationSeconds}s${asset.loop ? ', loop' : ''})\n`);
  try {
    const response = await requestAudioWithRetry(asset, apiKey);
    if (!response.ok) throw new GenerationError(response.status);
    const contentType = response.headers.get('content-type') ?? '';
    if (contentType && !contentType.startsWith('audio/') && contentType !== 'application/octet-stream') {
      throw new Error('response was not audio');
    }
    const bytes = Buffer.from(await response.arrayBuffer());
    // Never write a fake, empty or truncated file: the header and the size
    // are both checked before anything lands at the real path.
    if (!isMp3(bytes)) throw new Error('response was not a valid MP3');
    const temporaryPath = `${targetPath}.tmp`;
    await writeFile(temporaryPath, bytes);
    if (!(await isValidMp3File(temporaryPath))) throw new Error('generated MP3 failed local validation');
    await replaceWithBackup(temporaryPath, targetPath, asset.name);
  } catch (error) {
    await unlink(`${targetPath}.tmp`).catch(() => undefined);
    const reason = error instanceof GenerationError ? `HTTP ${error.status}` : (error?.message ?? 'unknown error');
    failures.push(`${asset.name} (${reason})`);
    process.stderr.write(`Mission 13 audio generation failed: ${asset.name}.mp3 (${reason})\n`);
  }
}

await reportCoverage();
if (failures.length > 0) {
  process.stderr.write(`\nFailures: ${failures.length}\n`);
  for (const failure of failures) process.stderr.write(`  - ${failure}\n`);
  process.stderr.write('Re-run the command to retry only the missing files.\n');
  process.exitCode = 1;
}

// ---------------------------------------------------------------------------
// Catalog helpers
// ---------------------------------------------------------------------------

function music(name, durationSeconds, prompt) {
  return { name, group: 'music', loop: true, durationSeconds, prompt: `${prompt} ${NEGATIVE_MUSIC}` };
}

function ambience(name, durationSeconds, prompt) {
  return { name, group: 'ambience', loop: true, durationSeconds, prompt: `${prompt} ${NEGATIVE_SFX}` };
}

function sfxLoop(name, durationSeconds, prompt) {
  return { name, group: 'sfx', loop: true, durationSeconds, prompt: `${prompt} ${NEGATIVE_SFX}` };
}

function sfxOneShot(name, durationSeconds, prompt) {
  return { name, group: 'sfx', loop: false, durationSeconds, prompt: `${prompt} ${NEGATIVE_SFX}` };
}

function directoryFor(group) {
  if (group === 'music') return musicDirectory;
  if (group === 'ambience') return ambienceDirectory;
  return sfxDirectory;
}

function targetPathFor(asset) {
  return join(directoryFor(asset.group), `${asset.name}.mp3`);
}

function getCategory(argv) {
  const option = argv.find((argument) => argument.startsWith('--category='));
  const value = option?.slice('--category='.length);
  if (!value) return null;
  if (value !== 'music' && value !== 'ambience' && value !== 'sfx') {
    process.stderr.write('Category must be music, ambience or sfx\n');
    process.exit(1);
  }
  return value;
}

function getRequestedNames(argv) {
  const option = argv.find((argument) => argument.startsWith('--only='));
  return new Set(
    (option?.slice('--only='.length) ?? '')
      .split(',')
      .map((name) => name.trim())
      .filter(Boolean)
  );
}

// ---------------------------------------------------------------------------
// Generation
// ---------------------------------------------------------------------------

async function requestAudioWithRetry(asset, key) {
  let response;
  for (let attempt = 0; attempt < 3; attempt += 1) {
    response = await requestAudio(asset, key);
    if (response.ok || (response.status !== 429 && response.status < 500)) return response;
    const retryAfter = Number(response.headers.get('retry-after'));
    const waitMs =
      Number.isFinite(retryAfter) && retryAfter > 0 ? Math.min(30000, retryAfter * 1000) : 1500 * (attempt + 1);
    process.stdout.write(`  retrying ${asset.name} in ${Math.round(waitMs / 1000)}s (HTTP ${response.status})\n`);
    await new Promise((resolve) => setTimeout(resolve, waitMs));
  }
  return response;
}

function requestAudio(asset, key) {
  const isMusic = asset.group === 'music';
  const endpoint = isMusic
    ? 'https://api.elevenlabs.io/v1/music?output_format=mp3_44100_128'
    : 'https://api.elevenlabs.io/v1/sound-generation?output_format=mp3_44100_128';
  const body = isMusic
    ? {
        prompt: asset.prompt,
        music_length_ms: asset.durationSeconds * 1000,
        model_id: 'music_v1',
        force_instrumental: true
      }
    : {
        text: asset.prompt,
        duration_seconds: asset.durationSeconds,
        // The sound-generation endpoint produces a genuinely seamless take
        // when this is set, which is what the ambience beds depend on.
        loop: asset.loop,
        prompt_influence: 0.55,
        model_id: 'eleven_text_to_sound_v2'
      };

  return fetch(endpoint, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', 'xi-api-key': key },
    body: JSON.stringify(body)
  });
}

/** Never destroy a previous take: it is copied aside before being replaced. */
async function replaceWithBackup(temporaryPath, targetPath, name) {
  if (await isValidMp3File(targetPath)) {
    await mkdir(backupDirectory, { recursive: true });
    await copyFile(targetPath, join(backupDirectory, `${name}.previous.mp3`));
  }
  await unlink(targetPath).catch(() => undefined);
  await rename(temporaryPath, targetPath);
}

async function reportCoverage() {
  let present = 0;
  const missing = [];
  for (const asset of catalog) {
    if (await isValidMp3File(targetPathFor(asset))) present += 1;
    else missing.push(`${asset.group}/${asset.name}.mp3`);
  }
  process.stdout.write(`\nMission 13 audio: ${present}/${catalog.length} file(s) present.\n`);
  if (missing.length > 0) {
    process.stdout.write('Still missing:\n');
    for (const name of missing) process.stdout.write(`  - ${name}\n`);
    process.stdout.write('The game runs regardless: missing cues fall back to existing sounds.\n');
  } else {
    process.stdout.write('All Mission 13 non-vocal audio is in place.\n');
  }
}

async function isValidMp3File(path) {
  try {
    const info = await stat(path);
    if (!info.isFile() || info.size < 1024) return false;
    return isMp3(await readFile(path));
  } catch {
    return false;
  }
}

function isMp3(bytes) {
  if (bytes.length < 1024) return false;
  return (
    (bytes[0] === 0x49 && bytes[1] === 0x44 && bytes[2] === 0x33) ||
    (bytes[0] === 0xff && (bytes[1] & 0xe0) === 0xe0)
  );
}
